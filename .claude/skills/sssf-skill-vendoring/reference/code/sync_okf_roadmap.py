#!/usr/bin/env python3
"""Regenerate the ticket tables in .okf/roadmap/ from .scratch/*/issues/.

Ticket status is a fact the issue files already hold, so a script copies it
and no agent transcribes it: live run 9c166220's documenter listed a resolved
ticket as `needs-triage`. Each feature directory `.scratch/<feature>/` gets a
`.okf/roadmap/<feature>.md` concept. Only the block between the
`okf-roadmap:tickets` markers is generated; everything outside it is narrative
the documenter owns and this script never touches. `.okf/roadmap/index.md` is
regenerated in full.

Deterministic (sorted, no timestamps), so a re-run with no ticket change is a
no-op. `adw_watch.py` runs it on every claim/resolve so the roadmap commit
carries the ticket's final state.

Usage: uv run scripts/sync_okf_roadmap.py [--check]
  --check  exit 1 (and change nothing) if any roadmap file is out of date
"""

from __future__ import annotations

import re
import sys
from dataclasses import dataclass
from pathlib import Path

SCRATCH = Path(".scratch")
ROADMAP = Path(".okf/roadmap")
BEGIN = "<!-- okf-roadmap:tickets (generated by scripts/sync_okf_roadmap.py; do not edit by hand) -->"
END = "<!-- /okf-roadmap:tickets -->"
DONE = {"resolved", "wontfix"}

STATUS_RE = re.compile(r"^\**Status:?\**:?\s*`?([a-z-]+)`?", re.MULTILINE)
SESSION_RE = re.compile(r"resolved by session `([0-9a-f]+)`")
TITLE_RE = re.compile(r"^#\s+(?:\d+:\s*)?(.+?)\s*$", re.MULTILINE)


@dataclass
class Ticket:
    number: str
    title: str
    status: str
    delivered: str
    path: Path


def read_ticket(path: Path) -> Ticket:
    text = path.read_text()
    title = TITLE_RE.search(text)
    status = STATUS_RE.search(text)
    sessions = SESSION_RE.findall(text)
    if sessions:
        delivered = f"session `{sessions[-1]}`"
    elif "Resolved by hand" in text or "Manually resolved" in text:
        delivered = "by hand"
    else:
        delivered = "—"
    return Ticket(
        number=path.name.split("-", 1)[0],
        title=title.group(1) if title else path.stem,
        status=status.group(1) if status else "unknown",
        delivered=delivered,
        path=path,
    )


def feature_title(feature: Path) -> str:
    """The roadmap concept's own `title:` once it exists, else the spec's H1,
    else the directory name."""
    concept = ROADMAP / f"{feature.name}.md"
    if concept.is_file():
        found = re.search(r"\A---\n.*?^title:\s*(.+?)\s*$.*?^---\n", concept.read_text(),
                          re.MULTILINE | re.DOTALL)
        if found:
            return found.group(1).strip("\"'")
    spec = feature / "spec.md"
    if spec.is_file():
        heading = TITLE_RE.search(spec.read_text())
        if heading:
            return re.sub(r"^Spec:\s*", "", heading.group(1))
    return feature.name.replace("-", " ").capitalize()


def tickets_block(tickets: list[Ticket]) -> str:
    done = sum(t.status in DONE for t in tickets)
    lines = [
        BEGIN,
        "## Tickets",
        "",
        f"{done} of {len(tickets)} resolved; {len(tickets) - done} open.",
        "",
        "| # | Ticket | Status | Delivered |",
        "|---|---|---|---|",
    ]
    for t in tickets:
        title = t.title.replace("|", "\\|")
        lines.append(f"| {t.number} | {title} (`{t.path.as_posix()}`) | `{t.status}` | {t.delivered} |")
    lines.append(END)
    return "\n".join(lines)


def new_concept(feature: Path, block: str) -> str:
    title = feature_title(feature)
    spec = feature / "spec.md"
    source = (spec if spec.is_file() else feature / "issues").as_posix()
    return "\n".join([
        "---",
        "type: Feature Roadmap",
        f"title: {title}",
        f"description: Roadmap for the {feature.name} feature, tickets under {feature.as_posix()}/issues/.",
        "status: stable",
        "sources:",
        f"  - id: {feature.name}-tickets",
        f"    resource: {source}",
        f"    title: {title}",
        "---",
        "",
        f"# {title}",
        "",
        block,
        "",
    ])


def without_hand_tables(body: str) -> str:
    """Drop `## Shipped` / `## Open` sections an agent wrote before this script
    owned the ticket table; the generated block replaces them."""
    return re.sub(r"^## (?:Shipped|Open)\n.*?(?=^## |\Z)", "", body, flags=re.MULTILINE | re.DOTALL)


def updated_concept(text: str, block: str) -> str:
    if BEGIN in text and END in text:
        head, rest = text.split(BEGIN, 1)
        return head + block + rest.split(END, 1)[1]
    text = without_hand_tables(text)
    match = re.search(r"^# .+\n", text, re.MULTILINE)   # insert right after the H1
    if not match:
        return text.rstrip("\n") + "\n\n" + block + "\n"
    rest = text[match.end():].lstrip("\n")
    return text[:match.end()] + "\n" + block + "\n\n" + rest


def index_text(features: list[tuple[Path, list[Ticket]]]) -> str:
    lines = ["# Roadmap", ""]
    for feature, tickets in features:
        done = sum(t.status in DONE for t in tickets)
        lines.append(f"* [{feature_title(feature)}]({feature.name}.md) - {done} of {len(tickets)} tickets resolved")
    return "\n".join(lines) + "\n"


def plan() -> dict[Path, str]:
    """Every roadmap file this script owns, mapped to its intended content."""
    features = []
    for feature in sorted(p for p in SCRATCH.iterdir() if (p / "issues").is_dir()):
        tickets = [read_ticket(p) for p in sorted((feature / "issues").glob("*.md"))]
        if tickets:
            features.append((feature, tickets))
    out: dict[Path, str] = {}
    for feature, tickets in features:
        path = ROADMAP / f"{feature.name}.md"
        block = tickets_block(tickets)
        out[path] = updated_concept(path.read_text(), block) if path.is_file() else new_concept(feature, block)
    out[ROADMAP / "index.md"] = index_text(features)
    return out


def main(argv: list[str]) -> int:
    check = "--check" in argv
    stale = [p for p, content in plan().items() if not p.is_file() or p.read_text() != content]
    if check:
        for p in stale:
            print(f"stale: {p}")
        return 1 if stale else 0
    ROADMAP.mkdir(parents=True, exist_ok=True)
    for p, content in plan().items():
        if not p.is_file() or p.read_text() != content:
            p.write_text(content)
            print(f"wrote {p}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
